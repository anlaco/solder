export const PATTERN_GRID_COLUMNS = 6;

/** Index in the grid of LabVIEW's default pattern, 4-2-2-4 (row 6, column 3: the one outlined in blue). */
const DEFAULT_PATTERN_INDEX = 32;
const DEFAULT_PATTERN_NAME = "4-2-2-4";

const idOfPattern = (index) => `pattern-${String(index + 1).padStart(2, "0")}`;

/** Every pattern, in grid order: `{ id, name, cells }`. `name` is only known for 4-2-2-4, otherwise `null`. */
export const CONNECTOR_PATTERNS = PATTERN_CELLS.map((cells, index) => ({
  id: idOfPattern(index),
  name: index === DEFAULT_PATTERN_INDEX ? DEFAULT_PATTERN_NAME : null,
  cells: cells.map(([left, top, right, bottom]) => ({ left, top, right, bottom })),
}));

/** The pattern whose name is the given one (`4-2-2-4`), or `undefined`. */
export const patternNamed = (name) => CONNECTOR_PATTERNS.find((pattern) => pattern.name === name);

/** Row and column (1-based) of a pattern in the grid. */
export const gridPosition = (patternId) => {
  const index = CONNECTOR_PATTERNS.findIndex((pattern) => pattern.id === patternId);
  return { row: Math.floor(index / PATTERN_GRID_COLUMNS) + 1, column: (index % PATTERN_GRID_COLUMNS) + 1 };
};
